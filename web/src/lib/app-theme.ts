export function getAntThemeConfig(dark: boolean): ThemeConfig {
    const color = dark ? neutral.dark : neutral.light;

    return {
        algorithm: dark ? antdTheme.darkAlgorithm : antdTheme.defaultAlgorithm,
        cssVar: { key: dark ? "dreamyo-dark" : "dreamyo-light" },
        token: {
            colorPrimary: color.primary,
            colorInfo: color.primary,
            colorLink: color.primary,
            colorLinkHover: color.primaryHover,
            colorLinkActive: color.primary,
            colorTextLightSolid: color.primaryText,
            colorBgLayout: color.layoutBg,
            colorBgContainer: color.containerBg,
            colorBorder: color.border,
            colorText: color.text,
            colorTextSecondary: color.textSecondary,
            borderRadius: 8,
        },
        components: {
            Button: {
                primaryShadow: "none",
            },
            Segmented: {
                itemSelectedBg: color.selectSelectedBg,
                itemSelectedColor: color.selectText,
                itemHoverBg: color.selectActiveBg,
                trackBg: dark ? "rgba(255, 255, 255, 0.045)" : "rgba(91, 111, 139, 0.1)",
            },
            Slider: {
                handleActiveColor: dark ? "#35cce1" : "#5e7ff1",
                handleActiveOutlineColor: dark ? "rgba(53, 204, 225, 0.22)" : "rgba(94, 127, 241, 0.18)",
                handleColor: dark ? "#35cce1" : "#5e7ff1",
                trackBg: dark ? "#24b9d2" : "#5e7ff1",
                trackHoverBg: dark ? "#58dec9" : "#35cce1",
            },
            Switch: {
                handleBg: "#ffffff",
            },
            Tabs: {
                inkBarColor: dark ? "#35cce1" : "#5e7ff1",
                itemActiveColor: color.selectText,
                itemHoverColor: dark ? "#d9f8ff" : "#1e4db7",
                itemSelectedColor: color.selectText,
            },
            Radio: {
                buttonCheckedBg: color.selectSelectedBg,
                buttonCheckedColorDisabled: color.textSecondary,
                buttonSolidCheckedBg: dark ? "#24b9d2" : "#5e7ff1",
                buttonSolidCheckedHoverBg: dark ? "#58dec9" : "#35cce1",
                buttonSolidCheckedActiveBg: dark ? "#188da4" : "#4565d0",
            },
            Menu: {
                itemActiveBg: color.menuBg,
                itemHoverBg: color.menuBg,
                itemSelectedBg: color.selectSelectedBg,
                itemSelectedColor: color.selectText,
                darkItemHoverBg: neutral.dark.menuBg,
                darkItemSelectedBg: neutral.dark.selectSelectedBg,
                darkItemSelectedColor: neutral.dark.selectText,
            },
            Select: {
                activeBorderColor: color.selectBorder,
                activeOutlineColor: color.selectOutline,
                borderRadiusLG: 8,
                borderRadiusSM: 6,
                boxShadowSecondary: color.selectShadow,
                controlItemBgActiveHover: color.selectSelectedBg,
                hoverBorderColor: color.selectBorder,
                optionActiveBg: color.selectActiveBg,
                optionHeight: 32,
                optionPadding: "5px 10px",
                optionSelectedBg: color.selectSelectedBg,
                optionSelectedColor: color.selectText,
                optionSelectedFontWeight: 400,
            },
            Cascader: {
                borderRadiusLG: 8,
                borderRadiusSM: 6,
                boxShadowSecondary: color.selectShadow,
                controlItemBgHover: color.selectActiveBg,
                optionPadding: "5px 10px",
                optionSelectedBg: color.selectSelectedBg,
                optionSelectedColor: color.selectText,
                optionSelectedFontWeight: 400,
            },
            TreeSelect: {
                borderRadiusLG: 8,
                borderRadiusSM: 6,
                boxShadowSecondary: color.selectShadow,
                nodeHoverBg: color.selectActiveBg,
                nodeHoverColor: color.selectText,
                nodeSelectedBg: color.selectSelectedBg,
                nodeSelectedColor: color.selectText,
            },
            Table: {
                rowSelectedBg: color.tableSelectedBg,
                rowSelectedHoverBg: color.tableSelectedHoverBg,
            },
        },
    };
}
